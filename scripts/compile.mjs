import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import solc from 'solc';
const root=path.resolve(import.meta.dirname,'..');
const sources={};
function walk(dir){for(const f of fs.readdirSync(dir,{withFileTypes:true})){
  const full=path.join(dir,f.name);
  if(f.isDirectory()) walk(full);
  else if(f.name.endsWith('.sol')) sources[path.relative(root,full).replaceAll('\\','/')]={content:fs.readFileSync(full,'utf8')};
}}
walk(path.join(root,'contracts'));
const settings={optimizer:{enabled:true,runs:200},evmVersion:'paris',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','metadata']}}};
const input={language:'Solidity',sources,settings};
const output=JSON.parse(solc.compile(JSON.stringify(input),{import(name){
  const resolved=path.resolve(root,'node_modules',name);
  if(!resolved.startsWith(path.resolve(root,'node_modules')+path.sep)) return {error:'Invalid import'};
  try {return {contents:fs.readFileSync(resolved,'utf8')}} catch{return {error:`Missing ${name}`}};
}}));
for(const e of output.errors??[]) console.log(e.formattedMessage);
if(output.errors?.some(e=>e.severity==='error'))process.exit(1);
fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
fs.mkdirSync(path.join(root,'reports'),{recursive:true});
const info=[];
for(const [file,contracts] of Object.entries(output.contracts)) for(const [name,c] of Object.entries(contracts)){
  if(!file.startsWith('contracts/'))continue;
  const artifact={name,source:file,compiler:solc.version(),abi:c.abi,bytecode:'0x'+c.evm.bytecode.object,deployedBytecode:'0x'+c.evm.deployedBytecode.object};
  fs.writeFileSync(path.join(root,'artifacts',name+'.json'),JSON.stringify(artifact,null,2));
  const bytes=c.evm.deployedBytecode.object.length/2;
  if(bytes>24576)throw new Error(`${name} exceeds EVM runtime size limit`);
  info.push({name,bytes,sha256:crypto.createHash('sha256').update(c.evm.bytecode.object).digest('hex')});
}
fs.writeFileSync(path.join(root,'artifacts','build-info.json'),JSON.stringify({compiler:solc.version(),settings,contracts:info},null,2));
console.log(`Compiled ${info.length} local contracts with ${solc.version()} (Paris EVM).`);

const abiSource=['HRPToken','TokenSale'].map(name=>{const a=JSON.parse(fs.readFileSync(path.join(root,'artifacts',name+'.json')));return `export const ${name==='HRPToken'?'hrpAbi':'saleAbi'} = ${JSON.stringify(a.abi)};`;}).join('\n');
fs.writeFileSync(path.join(root,'integration','abi.mjs'),'// Generated by compile.mjs\n'+abiSource+'\n');
